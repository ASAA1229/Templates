<#
.SYNOPSIS
  One-time (idempotent) database setup for the local production deployment on the PostgreSQL 18 service.
.DESCRIPTION
  Prompts for the postgres superuser password (kept only in memory, never written to disk), then creates:
    database  templates
    role      templates_migrator  owns the database/schema; used only by `prisma migrate deploy`
    role      templates_app       runtime role: DML only, cannot change schema
  Generated passwords are written to deploy/local-prod/.env.local-prod (git-ignored), readable only by the
  current Windows user. Re-running keeps existing passwords unless -RotatePasswords is given.
#>
param(
  [string]$PgHost = '127.0.0.1',
  [int]$PgPort = 5432,
  [switch]$RotatePasswords
)
. (Join-Path $PSScriptRoot 'common.ps1')
$pgBin = Find-PgBin
$psql = Join-Path $pgBin 'psql.exe'

$secure = Read-Host -AsSecureString 'PostgreSQL superuser (postgres) password'
$env:PGPASSWORD = [Net.NetworkCredential]::new('', $secure).Password

function New-Secret([int]$bytes = 24) {
  $b = New-Object byte[] $bytes
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  ([Convert]::ToBase64String($b)).TrimEnd('=').Replace('+', 'A').Replace('/', 'B')
}

try {
  $existing = @{}
  if (Test-Path $script:EnvFile) { $existing = Read-EnvFile }
  $keep = ($existing.ContainsKey('MIGRATOR_PASSWORD') -and -not $RotatePasswords)
  $migPw = if ($keep) { $existing['MIGRATOR_PASSWORD'] } else { New-Secret }
  $appPw = if ($keep) { $existing['APP_PASSWORD'] } else { New-Secret }
  $mfaKey = if ($existing.ContainsKey('MFA_ENCRYPTION_KEY')) { $existing['MFA_ENCRYPTION_KEY'] } else { New-Secret 32 }

  $conn = @('-h', $PgHost, '-p', $PgPort, '-U', 'postgres', '-v', 'ON_ERROR_STOP=1', '-X', '-q')
  # Passwords travel on stdin, never on a command line. Generated passwords are URL-safe alphanumerics.
  $roles = @"
DO `$`$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'templates_migrator') THEN CREATE ROLE templates_migrator LOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'templates_app') THEN CREATE ROLE templates_app LOGIN; END IF;
END `$`$;
ALTER ROLE templates_migrator PASSWORD '$migPw' NOSUPERUSER NOCREATEDB NOCREATEROLE;
ALTER ROLE templates_app PASSWORD '$appPw' NOSUPERUSER NOCREATEDB NOCREATEROLE;
"@
  $roles | & $psql @conn -d postgres
  if ($LASTEXITCODE -ne 0) { throw 'Could not create the roles (wrong superuser password?).' }

  $exists = & $psql @conn -d postgres -tA -c "SELECT 1 FROM pg_database WHERE datname = 'templates'"
  if (-not $exists) {
    & $psql @conn -d postgres -c 'CREATE DATABASE templates OWNER templates_migrator'
    if ($LASTEXITCODE -ne 0) { throw 'CREATE DATABASE failed.' }
  }
  $grants = @'
REVOKE ALL ON DATABASE templates FROM PUBLIC;
GRANT CONNECT ON DATABASE templates TO templates_app;
ALTER SCHEMA public OWNER TO templates_migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO templates_app;
ALTER DEFAULT PRIVILEGES FOR ROLE templates_migrator IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO templates_app;
ALTER DEFAULT PRIVILEGES FOR ROLE templates_migrator IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO templates_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO templates_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO templates_app;
'@
  $grants | & $psql @conn -d templates
  if ($LASTEXITCODE -ne 0) { throw 'Granting privileges failed.' }

  # Containers reach the host service as host.docker.internal.
  $lines = @(
    '# Generated by setup-db.ps1. Git-ignored. Do not share.',
    "MIGRATOR_PASSWORD=$migPw",
    "APP_PASSWORD=$appPw",
    "MFA_ENCRYPTION_KEY=$mfaKey",
    "MIGRATOR_DATABASE_URL=postgresql://templates_migrator:$migPw@host.docker.internal:$PgPort/templates?schema=public",
    "RUNTIME_DATABASE_URL=postgresql://templates_app:$appPw@host.docker.internal:$PgPort/templates?schema=public"
  )
  Set-Content -Path $script:EnvFile -Value $lines -Encoding ascii
  # Restrict to the current user only.
  $me = "$env:USERDOMAIN\$env:USERNAME"
  & icacls $script:EnvFile /inheritance:r /grant:r "${me}:(R,W)" | Out-Null
  Write-Host "Database 'templates' and roles ready. Wrote $script:EnvFile (current user only)."
  Write-Host 'If containers cannot connect, allow the Docker subnet in pg_hba.conf, for example:'
  Write-Host '  host  templates  templates_app,templates_migrator  172.16.0.0/12  scram-sha-256'
  Write-Host 'and make sure listen_addresses covers the host address (then reload the postgresql-x64-18 service).'
}
finally { Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue }
