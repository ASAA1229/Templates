<#
.SYNOPSIS
  Disposable PostgreSQL helpers for the Templates pipeline (Windows PowerShell 5.1 and PowerShell 7).
.DESCRIPTION
  -Action Migrate : applies the Prisma migrations to the disposable TEST database created by "npm run db:local -- init".
  -Action Cleanup : stops the project-local PostgreSQL cluster and removes .local and apps/api/.env (workspace only).
  Native-command exit codes are checked explicitly (Windows PowerShell 5.1 turns native stderr output into errors when
  $ErrorActionPreference is 'Stop').
#>
[CmdletBinding()]
param([Parameter(Mandatory = $true)][ValidateSet('Migrate', 'Cleanup')][string]$Action)

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
Set-Location -LiteralPath $repoRoot

function Invoke-Native {
  param([string]$File, [string[]]$Arguments)
  $previous = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  try {
    & $File @Arguments 2>&1 | ForEach-Object { Write-Host $_ }
    return $LASTEXITCODE
  } finally {
    $ErrorActionPreference = $previous
  }
}

if ($Action -eq 'Migrate') {
  $ErrorActionPreference = 'Stop'
  $envFile = Join-Path $repoRoot 'apps\api\.env'
  if (-not (Test-Path -LiteralPath $envFile -PathType Leaf)) { throw 'apps/api/.env was not generated by "npm run db:local -- init".' }
  $line = Get-Content -LiteralPath $envFile | Where-Object { $_ -match '^TEST_DATABASE_URL=' } | Select-Object -First 1
  if (-not $line) { throw 'TEST_DATABASE_URL was not generated in apps/api/.env.' }
  $match = [regex]::Match($line, '^TEST_DATABASE_URL="?([^"]+)"?$')
  if (-not $match.Success) { throw 'TEST_DATABASE_URL in apps/api/.env has an unexpected format.' }
  $env:DATABASE_URL = $match.Groups[1].Value
  try {
    $code = Invoke-Native 'npm.cmd' @('run', 'db:deploy', '-w', '@asaa/api')
    if ($code -ne 0) { throw "Applying migrations to the disposable test database failed (exit code $code)." }
  } finally {
    Remove-Item Env:DATABASE_URL -ErrorAction SilentlyContinue
  }
  Write-Host 'Disposable test database migrated.'
  exit 0
}

# Cleanup is best effort and never throws: a failed cleanup must not mask the real build result, but it is reported.
$dataDir = Join-Path $repoRoot '.local\pgdata'
if (Test-Path -LiteralPath $dataDir -PathType Container) {
  $code = Invoke-Native 'npm.cmd' @('run', 'db:local', '--', 'stop')
  if ($code -ne 0) {
    Write-Host "WARNING: 'npm run db:local -- stop' exited with $code; forcing an immediate PostgreSQL shutdown."
    $code = Invoke-Native 'pg_ctl' @('-D', $dataDir, '-m', 'immediate', 'stop')
    if ($code -ne 0) { Write-Host "WARNING: pg_ctl immediate stop exited with $code; the cluster may still be running." }
  }
  Remove-Item -Recurse -Force -LiteralPath (Join-Path $repoRoot '.local') -ErrorAction SilentlyContinue
}
Remove-Item -Force -LiteralPath (Join-Path $repoRoot 'apps\api\.env') -ErrorAction SilentlyContinue
Remove-Item -Recurse -Force -LiteralPath (Join-Path $repoRoot '.jenkins-temp') -ErrorAction SilentlyContinue
exit 0
